package com.billing.invoicehub;

import com.billing.invoicehub.entity.AppRole;
import com.billing.invoicehub.entity.AppUser;
import com.billing.invoicehub.repository.AppRoleRepository;
import com.billing.invoicehub.repository.AppUserRepository;
import com.billing.invoicehub.repository.AuditLogRepository;
import com.billing.invoicehub.service.EmployeeUserService;
import com.billing.invoicehub.service.StartupRoleMigration;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.TestPropertySource;
import org.springframework.transaction.annotation.Transactional;

import java.util.HashSet;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@TestPropertySource(properties = {
        "rate-limiting.enabled=false",
        "app.security.hibp.enabled=false"
})
@Transactional
public class SuperAdminStartupAndRoleManagementTest {

    @Autowired
    private StartupRoleMigration startupRoleMigration;

    @Autowired
    private EmployeeUserService userService;

    @Autowired
    private AppUserRepository userRepository;

    @Autowired
    private AppRoleRepository roleRepository;

    @Autowired
    private AuditLogRepository auditLogRepository;

    @Autowired
    private PasswordEncoder passwordEncoder;

    private AppRole roleAdmin;
    private AppRole roleSuperAdmin;
    private AppRole roleAccounts;

    @BeforeEach
    void setUp() {
        startupRoleMigration.ensureRequiredRolesExist();
        roleAdmin = roleRepository.findFirstByName("ROLE_ADMIN").orElseThrow();
        roleSuperAdmin = roleRepository.findFirstByName("ROLE_SUPER_ADMIN").orElseThrow();
        roleAccounts = roleRepository.findFirstByName("ROLE_ACCOUNTS").orElseThrow();
    }

    @Test
    @DisplayName("1. Roles are created through JPA once and idempotent on every start")
    void testRolesCreatedOnceIdempotently() {
        // Confirm both roles exist
        Optional<AppRole> superAdminOpt = roleRepository.findFirstByName("ROLE_SUPER_ADMIN");
        Optional<AppRole> accountsOpt = roleRepository.findFirstByName("ROLE_ACCOUNTS");

        assertTrue(superAdminOpt.isPresent(), "ROLE_SUPER_ADMIN must exist");
        assertTrue(accountsOpt.isPresent(), "ROLE_ACCOUNTS must exist");

        Long superAdminId = superAdminOpt.get().getId();
        Long accountsId = accountsOpt.get().getId();
        assertNotNull(superAdminId, "Role ID must be generated by JPA");
        assertNotNull(accountsId, "Role ID must be generated by JPA");

        long initialCount = roleRepository.count();

        // Run ensureRequiredRolesExist again (simulating subsequent startup)
        startupRoleMigration.ensureRequiredRolesExist();

        assertEquals(initialCount, roleRepository.count(), "Role count must not change on subsequent startup");
        assertEquals(superAdminId, roleRepository.findFirstByName("ROLE_SUPER_ADMIN").get().getId(), "Role ID must remain identical");
        assertEquals(accountsId, roleRepository.findFirstByName("ROLE_ACCOUNTS").get().getId(), "Role ID must remain identical");
    }

    @Test
    @DisplayName("2. Environment variable grants ROLE_SUPER_ADMIN to internal users without removing ROLE_ADMIN")
    void testEnvVarGrantsSuperAdminWithoutRemovingRoleAdmin() {
        String testUsername = "prod_admin_" + System.currentTimeMillis();
        AppUser adminUser = new AppUser();
        adminUser.setUsername(testUsername);
        adminUser.setEmail(testUsername + "@flowforce.test");
        adminUser.setPassword(passwordEncoder.encode("SecretPass123!@#"));
        adminUser.setUserDomain("INTERNAL");
        adminUser.setEnabled(true);
        adminUser.setRoles(new HashSet<>(Set.of(roleAdmin)));
        userRepository.saveAndFlush(adminUser);

        // Verify initial state: only ROLE_ADMIN
        AppUser loaded = userRepository.findByUsername(testUsername).orElseThrow();
        assertEquals(1, loaded.getRoles().size());
        assertTrue(loaded.getRoles().stream().anyMatch(r -> "ROLE_ADMIN".equals(r.getName())));
        assertFalse(loaded.getRoles().stream().anyMatch(r -> "ROLE_SUPER_ADMIN".equals(r.getName())));

        // Execute promotion via startup method with testUsername
        startupRoleMigration.promoteConfiguredSuperAdmins(testUsername);

        // Reload user: must have BOTH ROLE_ADMIN and ROLE_SUPER_ADMIN
        AppUser promoted = userRepository.findByUsername(testUsername).orElseThrow();
        assertEquals(2, promoted.getRoles().size(), "User must retain existing roles and receive ROLE_SUPER_ADMIN");
        assertTrue(promoted.getRoles().stream().anyMatch(r -> "ROLE_ADMIN".equals(r.getName())), "ROLE_ADMIN must NOT be removed");
        assertTrue(promoted.getRoles().stream().anyMatch(r -> "ROLE_SUPER_ADMIN".equals(r.getName())), "ROLE_SUPER_ADMIN must be added");

        // Verify audit log entry exists
        boolean auditFound = auditLogRepository.findAll().stream().anyMatch(log ->
                "AppUser".equals(log.getEntityType()) &&
                promoted.getId().equals(log.getEntityId()) &&
                "ROLE_GRANTED".equals(log.getAction())
        );
        assertTrue(auditFound, "Promotion must be recorded in the audit log");

        // Running again is idempotent and does not duplicate
        startupRoleMigration.promoteConfiguredSuperAdmins(testUsername);
        AppUser again = userRepository.findByUsername(testUsername).orElseThrow();
        assertEquals(2, again.getRoles().size());

        // Empty, null, or whitespace-only usernames do nothing
        startupRoleMigration.promoteConfiguredSuperAdmins("");
        startupRoleMigration.promoteConfiguredSuperAdmins("   ");
        startupRoleMigration.promoteConfiguredSuperAdmins(null);

        // Non-internal user (e.g. VENDOR) is skipped
        String vendorUsername = "vendor_" + System.currentTimeMillis();
        AppUser vendorUser = new AppUser();
        vendorUser.setUsername(vendorUsername);
        vendorUser.setEmail(vendorUsername + "@vendor.test");
        vendorUser.setPassword(passwordEncoder.encode("SecretPass123!@#"));
        vendorUser.setUserDomain("VENDOR");
        vendorUser.setEnabled(true);
        AppRole roleVendor = roleRepository.findFirstByName("ROLE_VENDOR").orElseGet(() -> {
            AppRole r = new AppRole();
            r.setName("ROLE_VENDOR");
            return roleRepository.save(r);
        });
        vendorUser.setRoles(new HashSet<>(Set.of(roleVendor)));
        userRepository.saveAndFlush(vendorUser);

        startupRoleMigration.promoteConfiguredSuperAdmins(vendorUsername);
        AppUser vendorCheck = userRepository.findByUsername(vendorUsername).orElseThrow();
        assertFalse(vendorCheck.getRoles().stream().anyMatch(r -> "ROLE_SUPER_ADMIN".equals(r.getName())),
                "Vendor accounts must never be granted ROLE_SUPER_ADMIN");
    }

    @Test
    @DisplayName("3. Nobody can remove the last SUPER_ADMIN (cannot delete, downgrade role, or disable)")
    void testLastSuperAdminCannotBeRemoved() {
        // Remove existing SUPER_ADMIN role from any users so we have complete control
        List<AppUser> existingSuperAdmins = userRepository.findByRoles_NameOrderByIdDesc("ROLE_SUPER_ADMIN");
        for (AppUser sa : existingSuperAdmins) {
            sa.getRoles().removeIf(r -> "ROLE_SUPER_ADMIN".equals(r.getName()));
            userRepository.saveAndFlush(sa);
        }

        // Create exactly ONE active Super Admin
        String loneUsername = "lone_superadmin_" + System.currentTimeMillis();
        AppUser newSuper = new AppUser();
        newSuper.setUsername(loneUsername);
        newSuper.setEmail(loneUsername + "@company.test");
        newSuper.setPassword(passwordEncoder.encode("SecretPass123!@#"));
        newSuper.setUserDomain("INTERNAL");
        newSuper.setEnabled(true);
        newSuper.setRoles(new HashSet<>(Set.of(roleSuperAdmin)));
        final AppUser loneSuperAdmin = userRepository.saveAndFlush(newSuper);

        assertEquals(1, userRepository.findByRoles_NameOrderByIdDesc("ROLE_SUPER_ADMIN").size(), "Should have exactly 1 Super Admin");

        final AppUser actor = loneSuperAdmin;
        final Long superAdminId = loneSuperAdmin.getId();

        // Attempt 1: Try to downgrade role from ROLE_SUPER_ADMIN to ROLE_ADMIN -> Must fail
        IllegalStateException roleEx = assertThrows(IllegalStateException.class, () ->
                userService.updateUser(superAdminId, null, "Lone Super", loneUsername + "@company.test", "ROLE_ADMIN", true, actor)
        );
        assertTrue(roleEx.getMessage().toLowerCase().contains("super admin"), "Error message should mention super admin protection");

        // Attempt 2: Try to disable the last active Super Admin via updateUser (enabled=false) -> Must fail
        IllegalStateException disableEx1 = assertThrows(IllegalStateException.class, () ->
                userService.updateUser(superAdminId, null, "Lone Super", loneUsername + "@company.test", "ROLE_SUPER_ADMIN", false, actor)
        );
        assertTrue(disableEx1.getMessage().toLowerCase().contains("active super admin"), "Error message should mention active super admin protection");

        // Attempt 3: Try to toggle the last active Super Admin to disabled -> Must fail
        IllegalStateException disableEx2 = assertThrows(IllegalStateException.class, () ->
                userService.toggleUserEnabled(superAdminId, actor)
        );
        assertTrue(disableEx2.getMessage().toLowerCase().contains("active super admin"));

        // Attempt 4: Try to delete the last Super Admin -> Must fail
        // (Even if an actor calls delete, the last super admin cannot be deleted)
        AppUser otherAdmin = new AppUser();
        otherAdmin.setUsername("temp_admin_" + System.currentTimeMillis());
        otherAdmin.setEmail("temp_admin@company.test");
        otherAdmin.setPassword(passwordEncoder.encode("SecretPass123!@#"));
        otherAdmin.setUserDomain("INTERNAL");
        otherAdmin.setEnabled(true);
        otherAdmin.setRoles(new HashSet<>(Set.of(roleSuperAdmin))); // temporarily super admin so it passes access check
        otherAdmin = userRepository.saveAndFlush(otherAdmin);

        // Now we have 2 super admins: otherAdmin and loneSuperAdmin
        assertEquals(2, userRepository.findByRoles_NameOrderByIdDesc("ROLE_SUPER_ADMIN").size());

        // Deleting otherAdmin succeeds because loneSuperAdmin is still there
        userService.deleteUser(otherAdmin.getId(), loneSuperAdmin);
        assertEquals(1, userRepository.findByRoles_NameOrderByIdDesc("ROLE_SUPER_ADMIN").size());

        // Now with loneSuperAdmin as the only super admin left, deleting it must fail
        IllegalStateException deleteEx = assertThrows(IllegalStateException.class, () ->
                userService.deleteUser(superAdminId, loneSuperAdmin)
        );
        assertTrue(deleteEx.getMessage().toLowerCase().contains("super admin"));
    }
}